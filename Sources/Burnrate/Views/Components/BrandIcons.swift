                Image(nsImage: image)
                    .renderingMode(.template)
                    .resizable()
                    .interpolation(.high)
                    .aspectRatio(contentMode: .fit)
            } else {
                Image(systemName: "questionmark.circle.fill")
                    .font(.system(size: size * 0.7))
            }
        }
        .frame(width: size, height: size)
